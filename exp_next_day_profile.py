import sys
import warnings

import numpy as np
import pandas as pd

import fit_model as F
import model as M
import signals as S

warnings.filterwarnings("ignore")
REF = M.OUTLOOK_REF_HOUR
TARGETS = (("00:30", 4.0), ("06:00", 9.5), ("08:00", 11.5), ("10:00", 13.5), ("12:00", 15.5), ("14:00", 17.5), ("16:00", 19.5), ("18:00", 21.5), ("20:30", 24.0))


def score(X, y):
    yu, yd = (y >= M.OUTLOOK_SMALL).astype(float), (y <= -M.OUTLOOK_SMALL).astype(float)
    pr, pf = F._wf_proba(X, yu), F._wf_proba(X, yd)
    ok = ~np.isnan(pr)
    y, yu, yd, pr, pf = y[ok], yu[ok], yd[ok], pr[ok], pf[ok]
    up, dn = (pr >= M.OUTLOOK_MIN_P) & (pr > pf), (pf >= M.OUTLOOK_MIN_P) & (pf > pr)
    c, s = up | dn, np.where(up, y, -y)
    first = np.arange(len(y)) < len(y) // 2
    r = lambda m: float((s[m] >= M.OUTLOOK_SMALL).mean()) if m.sum() else float("nan")
    e = {"auc": float(np.nanmean([F.auc(yu, pr), F.auc(yd, pf)])), "share": float(c.mean()), "right": r(c),
         "wrong": float((s[c] <= -M.OUTLOOK_SMALL).mean()) if c.sum() else float("nan"), "h1": r(c & first), "h2": r(c & ~first),
         "up": float(yu.mean()), "dn": float(yd.mean()), "n": int(len(y)), "n_up": int(up.sum()), "n_dn": int(dn.sum()),
         "r_up": float((y[up] >= M.OUTLOOK_SMALL).mean()) if up.sum() else float("nan"), "r_dn": float((y[dn] <= -M.OUTLOOK_SMALL).mean()) if dn.sum() else float("nan")}
    e["ok"] = bool(e["auc"] >= 0.70 and e["right"] >= 0.60 and e["wrong"] <= 0.12 and e["share"] >= 0.25 and min(e["h1"], e["h2"]) >= 0.55)
    return e


def line(label, tag, e):
    print(f"{label:<12}{tag:<4}{e['auc']:>6.3f}{e['share']:>7.0%}{e['right']:>6.0%}{e['wrong']:>6.0%}{e['h1']:>7.0%}{e['h2']:>7.0%}"
          f"{e['up']:>8.0%}{e['dn']:>6.0%}   ทายขึ้น {e['n_up']:>3} ถูก {e['r_up']:.0%} · ทายลง {e['n_dn']:>3} ถูก {e['r_dn']:.0%}  {'ผ่าน' if e['ok'] else '-'}", flush=True)


def main():
    prices, tables = F.load(sys.argv[1])
    book = S.PriceBook(prices)
    head = f"{'เป้าหมาย':<12}{'ชุด':<4}{'AUC':>6}{'ฟันธง':>7}{'ถูก':>6}{'ผิด':>6}{'ครึ่ง1':>7}{'ครึ่ง2':>7}{'ขึ้นจริง':>8}{'ลงจริง':>6}"
    for fuel in S.FUELS:
        print(f"\n== {fuel} ก : ราคา ณ เวลา T ของวันพรุ่งนี้ เทียบราคา 20:30 คืนนี้\n{head}")
        for name, hz in TARGETS:
            for v2 in (False, True):
                df = F.build_outlook_dataset(book, tables, fuel, hz, REF, v2=v2)
                X = np.vstack([(M.vectorize_v2 if v2 else M.vectorize)(r) for r in df.to_dict("records")])
                line(f"พรุ่งนี้ {name}", "v2" if v2 else "v1", score(X, df.y.to_numpy()))
        print(f"\n== {fuel} ข : ราคา 16:00 พรุ่งนี้ เทียบราคา 08:00 พรุ่งนี้ (ทาย ณ 20:30 คืนนี้)\n{head}")
        for v2 in (False, True):
            df = F.build_outlook_dataset(book, tables, fuel, 19.5, REF, v2=v2)
            am = book.min_at(fuel, [d + pd.Timedelta(days=1, hours=8) for d in df.date]).to_numpy()
            pm = book.min_at(fuel, [d + pd.Timedelta(days=1, hours=16) for d in df.date]).to_numpy()
            keep = ~(np.isnan(am) | np.isnan(pm))
            X = np.vstack([(M.vectorize_v2 if v2 else M.vectorize)(r) for r in df[keep].to_dict("records")])
            line("บ่าย−เช้า", "v2" if v2 else "v1", score(X, (pm - am)[keep]))


if __name__ == "__main__":
    main()
