import sys
import warnings

import numpy as np
import pandas as pd

import fit_model as F
import model as M
import signals as S

warnings.filterwarnings("ignore")
HOURS = (6.0, 8.0, 10.0, 12.0, 14.0, 15.5, 17.0, 18.0, 19.0, 20.5, 22.0)


def evaluate(book, tables, fuel, hour, v2):
    df = F.build_outlook_dataset(book, tables, fuel, 24, hour, v2=v2)
    recs = df.to_dict("records")
    X = np.vstack([(M.vectorize_v2 if v2 else M.vectorize)(r) for r in recs])
    y = df.y.to_numpy()
    yu, yd = (y >= M.OUTLOOK_SMALL).astype(float), (y <= -M.OUTLOOK_SMALL).astype(float)
    pr, pf = F._wf_proba(X, yu), F._wf_proba(X, yd)
    ok = ~np.isnan(pr)
    y, yu, yd, pr, pf = y[ok], yu[ok], yd[ok], pr[ok], pf[ok]
    up, dn = (pr >= M.OUTLOOK_MIN_P) & (pr > pf), (pf >= M.OUTLOOK_MIN_P) & (pf > pr)
    c, s = up | dn, np.where(up, y, -y)
    h = len(y) // 2
    first = np.arange(len(y)) < h
    r = lambda m: float((s[m] >= M.OUTLOOK_SMALL).mean()) if m.sum() else float("nan")
    out = {"n": len(y), "auc": float(np.nanmean([F.auc(yu, pr), F.auc(yd, pf)])), "auc_up": F.auc(yu, pr), "auc_dn": F.auc(yd, pf),
           "share": float(c.mean()), "right": r(c), "wrong": float((s[c] <= -M.OUTLOOK_SMALL).mean()) if c.sum() else float("nan"),
           "h1": r(c & first), "h2": r(c & ~first), "flat": float((np.abs(y) < M.OUTLOOK_SMALL).mean())}
    out["ok"] = bool(out["auc"] >= 0.70 and out["right"] >= 0.60 and out["wrong"] <= 0.12 and out["share"] >= 0.25 and min(out["h1"], out["h2"]) >= 0.55)
    return out


def main():
    prices, tables = F.load(sys.argv[1])
    book = S.PriceBook(prices)
    for fuel in S.FUELS:
        print(f"\n== {fuel} : แนวโน้ม 24 ชม. ตามเวลาตัดสินใจ")
        print(f"{'เวลา':<7}{'ชุด':<4}{'AUC':>6}{'ขึ้น':>6}{'ลง':>6}{'ฟันธง':>7}{'ถูก':>6}{'ผิด':>6}{'ครึ่ง1':>7}{'ครึ่ง2':>7}{'นิ่งจริง':>9}  ผล")
        for hour in HOURS:
            for v2 in (False, True):
                e = evaluate(book, tables, fuel, hour, v2)
                print(f"{int(hour):02d}:{int(round(hour % 1 * 60)):02d}  {'v2' if v2 else 'v1':<4}{e['auc']:>6.3f}{e['auc_up']:>6.2f}{e['auc_dn']:>6.2f}{e['share']:>7.0%}{e['right']:>6.0%}{e['wrong']:>6.0%}"
                      f"{e['h1']:>7.0%}{e['h2']:>7.0%}{e['flat']:>9.0%}  {'ผ่าน' if e['ok'] else '-'}", flush=True)


if __name__ == "__main__":
    main()
